-- Run this script in Supabase Dashboard -> SQL Editor -> New query.
-- SmartSpend uses a server-side Supabase secret key from Flask.
-- Never expose that key in frontend JavaScript or commit it to Git.

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    name text not null,
    email text not null unique,
    password_hash text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.expenses (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    title text not null,
    amount numeric(12, 2) not null check (amount > 0),
    category text not null,
    expense_date date not null,
    created_at timestamptz not null default now()
);

create table if not exists public.budgets (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    month text not null,
    amount numeric(12, 2) not null check (amount > 0),
    unique (user_id, month)
);

create index if not exists expenses_user_date_idx
    on public.expenses (user_id, expense_date desc);

-- This starter app authenticates users with Flask sessions and performs
-- database access only from the Flask server using SUPABASE_SECRET_KEY.
-- Keep RLS enabled and do not expose the secret key to the browser.
alter table public.users enable row level security;
alter table public.expenses enable row level security;
alter table public.budgets enable row level security;
